async function sha256Hex(text) {
  const enc = new TextEncoder().encode(text);
  const digest = await crypto.subtle.digest("SHA-256", enc);
  return Array.from(new Uint8Array(digest))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

async function notifyDiscordKeyUsed(key) {
  const payload = {
    embeds: [
      {
        title: "Key Used!",
        description: `A key has been used:\n\`${key}\``,
        color: 0x57f287,
        timestamp: new Date().toISOString(),
      },
    ],
  };

  try {
    await fetch(getWebhookUrl(), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
  } catch (err) {
    console.warn("Discord webhook failed:", err);
  }
}

export async function validateKey(inputKey) {
  const normalized = inputKey.trim().toUpperCase();
  const hash = await sha256Hex(normalized);
  const isValid = VALID_KEY_HASHES.includes(hash);

  if (isValid) {
    await chrome.storage.local.set({ licenseKey: normalized, keyVerified: true });
    await notifyDiscordKeyUsed(normalized);
  }

  return isValid;
}

export async function isKeyVerified() {
  const { keyVerified } = await chrome.storage.local.get("keyVerified");
  return !!keyVerified;
}